#!/usr/bin/env node
/**
 * Generate the typed API client from the pinned OpenAPI document (ADR 0005).
 *
 * Inputs  : openapi/revv-api.json   (copied from revv-api at a pinned version, committed)
 * Outputs : src/api/generated/schema.d.ts   (openapi-typescript)
 *           src/api/generated/client.ts      (thin openapi-fetch wrapper)
 *           openapi/.spec-hash                (sha256, matches tools/check-openapi-drift.mjs)
 *
 * Runs as prestart / pretest. The generated client is committed so its diff is
 * reviewable; check-openapi-drift.mjs fails CI if the client and spec disagree.
 */

import { createHash } from 'node:crypto'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

import openapiTS, { astToString } from 'openapi-typescript'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const specPath = join(root, 'openapi', 'revv-api.json')
const hashPath = join(root, 'openapi', '.spec-hash')
const outDir = join(root, 'src', 'api', 'generated')

const raw = await readFile(specPath, 'utf8')

const ast = await openapiTS(JSON.parse(raw), { alphabetize: true })
const schema = `${astToString(ast).trimEnd()}\n`

await mkdir(outDir, { recursive: true })
await writeFile(
  join(outDir, 'schema.d.ts'),
  `// Generated by scripts/generate-client.mjs. Do not edit.\n${schema}`,
  'utf8',
)

const client = `// Generated by scripts/generate-client.mjs. Do not edit.
// The one way this app talks to revv-api. No ad-hoc fetch (engineering-standards.md).
import createClient from 'openapi-fetch'

import { apiBaseUrl } from '../base-url'
import type { paths } from './schema'

// \`credentials: 'include'\` sends the Better Auth session cookie: it is the auth path
// on web (expo-secure-store has no bearer token there). On native there is no cookie,
// so the auth middleware's bearer header still does the work.
export const api = createClient<paths>({ baseUrl: apiBaseUrl, credentials: 'include' })
export type { paths }
`
await writeFile(join(outDir, 'client.ts'), client, 'utf8')

const normalized = JSON.stringify(sortKeys(JSON.parse(raw)))
const hash = createHash('sha256').update(normalized).digest('hex')
await writeFile(hashPath, `${hash}\n`, 'utf8')

console.log(`generate-client: wrote src/api/generated/{schema.d.ts,client.ts} + openapi/.spec-hash (${hash})`)

function sortKeys(value) {
  if (Array.isArray(value)) return value.map(sortKeys)
  if (value && typeof value === 'object') {
    return Object.fromEntries(
      Object.keys(value)
        .sort()
        .map((k) => [k, sortKeys(value[k])]),
    )
  }
  return value
}
